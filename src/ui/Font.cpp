GLuint Font::texture = 0;
bool Font::initialized = false;

bool Font::init()
{
    if (initialized) return true;

    // Create an 8x8 * 96 character texture atlas (768 x 8)
    const int atlasWidth = 8 * 96;
    const int atlasHeight = 8;
    std::vector<unsigned char> pixels(atlasWidth * atlasHeight, 0);

    for (int c = 0; c < 96; ++c)
    {
        for (int row = 0; row < 8; ++row)
        {
            unsigned char bits = font8x8_basic[c][row];
            for (int col = 0; col < 8; ++col)
            {
                if (bits & (1 << col))
                {
                    int x = c * 8 + col;
                    int y = row;
                    pixels[y * atlasWidth + x] = 255;
                }
            }
        }
    }

    glGenTextures(1, &texture);
    glBindTexture(GL_TEXTURE_2D, texture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RED, atlasWidth, atlasHeight, 0, GL_RED, GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);

    initialized = true;
    return true;
}

void Font::shutdown()
{
    if (texture)
    {
        glDeleteTextures(1, &texture);
        texture = 0;
    }
    initialized = false;
}

void Font::draw(UIContext& ctx, const glm::vec2& pos, const std::string& text, const glm::vec4& color, float scale)
{
    if (!initialized || texture == 0) return;

    const float charW = 8.0f * scale;
    const float charH = 8.0f * scale;
    const float atlasWidth = 8.0f * 96.0f;   // 768
    const float atlasHeight = 8.0f;

    float x = pos.x;
    float y = pos.y;

    for (unsigned char c : text)
    {
        if (c == '\n')
        {
            x = pos.x;
            y += charH + 2.0f * scale;
            continue;
        }

        // Only draw printable ASCII (32..127)
        if (c < 32 || c > 127)
        {
            x += charW;
            continue;
        }

        int index = c - 32;          // 0..95
        float u0 = (index * 8.0f) / atlasWidth;
        float u1 = ((index + 1) * 8.0f) / atlasWidth;
        float v0 = 0.0f;
        float v1 = 1.0f;

        ctx.drawTexturedRect(
            { x, y },
            { charW, charH },
            color,
            texture,
            { u0, v0 },
            { u1, v1 }
        );

        x += charW;
    }
}

float Font::getTextWidth(const std::string& text, float scale)
{
    return static_cast<float>(text.size()) * 8.0f * scale;
}

float Font::getLineHeight(float scale)
{
    return 8.0f * scale;
}